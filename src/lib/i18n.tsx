const dicts: Record<Lang, Record<DictKey, string>> = { en, ar };

export interface I18n {
  lang: Lang;
  dir: 'rtl' | 'ltr';
  t: (key: DictKey, vars?: Record<string, string | number>) => string;
  /** Picks the localized value of a bilingual field with fallback to the other language. */
  pick: (rec: Record<string, unknown> | null | undefined, field: string) => string;
  money: (amount: number) => string;
  num: (n: number) => string;
  date: (iso: string, opts?: Intl.DateTimeFormatOptions) => string;
}

const I18nContext = createContext<I18n | null>(null);

export function makeI18n(lang: Lang, currency = 'SAR'): I18n {
  const locale = lang === 'ar' ? 'ar-SA-u-nu-latn' : 'en-GB';
  return {
    lang,
    dir: lang === 'ar' ? 'rtl' : 'ltr',
    t: (key, vars) => {
      let s = dicts[lang][key] ?? en[key] ?? key;
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
      return s;
    },
    pick: (rec, field) => {
      if (!rec) return '';
      const primary = rec[`${field}_${lang}`];
      const other = rec[`${field}_${lang === 'ar' ? 'en' : 'ar'}`];
      return String((primary as string) || (other as string) || '');
    },
    money: (amount) => formatMoney(amount, currency, lang),
    num: (n) => new Intl.NumberFormat(locale).format(n),
    date: (iso, opts) => new Intl.DateTimeFormat(locale, opts ?? { dateStyle: 'medium', timeStyle: 'short' }).format(new Date(iso)),
  };
}

export function I18nProvider({ lang, currency, children }: { lang: Lang; currency?: string; children: ReactNode }) {
  const value = useMemo(() => makeI18n(lang, currency), [lang, currency]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18n {
  const v = useContext(I18nContext);
  if (!v) throw new Error('useI18n outside I18nProvider');
  return v;
}
